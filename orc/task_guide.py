"""What agents are told about creating cards: the short note in a session's system prompt, the full
guide behind `orc task guide`, and the same guide as a Claude Code skill for sessions outside orc.
"""
from __future__ import annotations

import shlex
import sys
from pathlib import Path

from orc.config import default_data_dir

SKILL_NAME = "orc-tasks"
SKILL_MARKER = "<!-- generated by `orc task install-skill` -->"


def cli_command(data_dir: Path) -> str:
    """How to run this very orc from anywhere: a session's PATH may not have it, and `uv run orc` in a
    worktree would be a different copy with a different data directory."""
    exe = Path(sys.executable)  # not resolved: a virtualenv's python is a symlink, and its location is the point
    script = exe.parent / "orc"
    command = shlex.join([str(script)] if script.is_file() else [str(exe), "-m", "orc.main"])
    if Path(data_dir).resolve() != default_data_dir().resolve():
        command = f"ORC_DATA_DIR={shlex.quote(str(Path(data_dir).resolve()))} {command}"
    return command


HANDOFF_RULE = (
    "Handing in the work: as your last action, after committing and running the verify command, run `{cmd} task done` "
    "as a command of its own, from your working copy, with nothing chained to it. Then end your turn with a message "
    "that says what was done, in the same language as the task description: it becomes the summary. If you stop for "
    "the owner's answer, decision or check, the work is not finished: end your turn with the question and do not run "
    "it. If you cannot complete the work, run `{cmd} task fail --reason \"TEXT\"`, with the reason on one line. Both "
    "commands are allowed in every permission mode, so try them even if other commands are denied. A line break, `$` "
    "or a backtick in an argument can get them denied: if that happens, run them again in this plain form. The "
    "orchestrator takes the state of the card from these commands, not from your words. To hand the owner a file as "
    "the result (a report, a screenshot, a built archive), run `{cmd} task attach PATH` before `task done`: files "
    "left in the working copy are lost when it is cleaned up. To wait for a time or for another card without "
    "holding a worker slot, run `{cmd} task wakeup --in 30m` (or `--at TIME`, or `--card N`, with `--note \"TEXT\"`) "
    "as your last action instead of `task done`, and end your turn: the session resumes here when it wakes."
)


def handoff_permissions(data_dir: Path) -> list[str]:
    """Allow rules for the commands of HANDOFF_RULE, in the form that rule tells the agent to run: done, fail,
    attach and wakeup."""
    command = cli_command(data_dir)
    return [f"Bash({command} task done:*)", f"Bash({command} task fail:*)", f"Bash({command} task attach:*)",
            f"Bash({command} task wakeup:*)"]


def session_note(data_dir: Path, task_id: int | None = None) -> str:
    """The block of a session's system prompt. Short on purpose: it costs tokens in every session, and
    only a few of them will need the details."""
    command = cli_command(data_dir)
    own = f" This session works on card #{task_id}." if task_id is not None else ""
    note = (f"Board access: you can add and change cards on this orchestrator's board with `{command} task`.{own} Each card is a "
            f"separate session in its own worktree. Create cards when the assignment or the owner asks for it, or when "
            f"the work is too large for one session and splits into steps that can each be verified. Otherwise just do "
            f"the work here. Run `{command} task guide` before your first card: it covers parameters, links, the base "
            f"branch and how to decompose a feature.")
    # Here and not only in the prompt template: a project can replace the template.
    return f"{note}\n\n{HANDOFF_RULE.format(cmd=command)}" if task_id is not None else note


GUIDE = """# Creating and changing cards on the orc board

Each card is a separate Claude Code session in its own git worktree. It sees only its assignment and
what has been merged into its base branch, not this conversation.

Commands (add --json to any of them for machine-readable output):

    {cmd} task context                 where you stand: project, base branch, agents, open cards
    {cmd} task add "Title" --description-file spec.txt [--agent NAME] [--after ID] [--status todo]
    {cmd} task batch plan.json         several linked cards, all or none
    {cmd} task link 12 --after 11      add or remove blockers of a card that has not started
    {cmd} task list                    the cards of the project (--status, --archived, --project, --label)
    {cmd} task show 12                 one card in full
    {cmd} task edit 12 --title "..." --description-file spec.txt --agent NAME --priority high
    {cmd} task move 12 --to OTHER      move a card that has not started to another project
    {cmd} task archive 12              take a card off the board; `unarchive` brings it back
    {cmd} task delete 12 --yes         delete for good
    {cmd} task done [--summary TEXT]   hand in the card you are in, as your last action
    {cmd} task fail --reason TEXT      say that the card you are in cannot be completed
    {cmd} task attach FILE...          hand in files as the result (report, screenshot, archive) before `done`
    {cmd} task wakeup --card 12        sleep without a worker slot until #12 is done (or --in 30m, --at TIME)

The project comes from the current folder. Pass --project NAME elsewhere. Wherever a card number is
expected, `current` means the card you are in.

## Changing cards

- `edit` changes only the fields you pass. `--clear FIELD` empties one (agent, verify_cmd,
  start_after, start_before, start_date, due_date, parent, stage, wake_on_children), so the agent's or the project's value applies
  again. `--label NAME` adds a label (created if missing) and `--remove-label NAME` takes one off; `--start-date`
  and `--due-date` (YYYY-MM-DD) set the plan, which the queue never reads. Labels and dates can change in any
  status. `--base` works until the card starts. Blockers are changed with `link`, never with `edit`.
- Subtasks. A card you create is a subtask of the card you are in: the owner sees it under yours, with
  progress. `add --parent ID` puts it under another card, `add --no-parent` makes it top-level, and
  `edit --parent ID` / `edit --clear parent` change it later, in any status. A parent is grouping only:
  it does not hold the queue, so a card that needs another's work still waits for it with `--after`.
- Stages. Subtasks of one parent can have a stage number: `add --stage N`, `edit --stage N` / `edit --clear stage`,
  or `"stage": N` per card in a batch. A stage starts when every card of the previous stage is done (merged), so
  five parallel cards after three need no 15 links. A failed card holds the next stage. It works only among
  siblings, and a card without a stage is not part of it. Use `--after` for a dependency across parents.
- Hearing back from subtasks. A card that split its work usually finishes before the pieces do. `edit current
  --wake-on-children` asks orc to wake it once every subtask is done: the card goes back to the queue (it waits
  for a free worker slot like any rework), you check the result and start the next step. A failed subtask holds
  the wake until the owner retries or closes it; a card is woken at most three times. Off unless you ask or the
  project says so, and your working copy must still exist then, so hand in with `orc task done` as usual.
- `edit --status todo` sends a card to work, so do it only when the assignment says so. A card needs an
  agent and a description first, and a card that your chain of agents created too deep stays in the
  backlog for the owner. Taking the agent off a queued card puts it back in the backlog.
- `move --to PROJECT` works for a card in the backlog or To do that has no session yet. It takes the
  base branch of the new project (or `--base`), keeps a shared agent and drops one that belongs to the
  old project. Cards that waited for it keep waiting, but across projects only the order applies.
- Prefer `archive` to `delete`: it can be undone. `delete` also removes the card's worktree and branch,
  needs `--yes`, and needs `--force` for a card being worked on. Do not delete your own card.

## Backlog or To do

Cards land in the backlog by default, and the owner decides when they run. Use status "todo" only when
the assignment says the work should run without the owner's go-ahead.

## A batch

    {{
      "sequential": true,
      "target_branch": "feature/export",
      "create_target_from": "main",
      "defaults": {{"agent": "Implementer", "status": "todo"}},
      "tasks": [
        {{"ref": "schema", "title": "Export: schema", "description": "the complete assignment"}},
        {{"ref": "api", "title": "Export: API", "description": "...", "agent": "Senior"}},
        {{"title": "Export: UI", "description": "...", "depends_on": [214]}}
      ]
    }}

- `sequential`: each card waits for the previous one. For anything else, use `depends_on` per card:
  a `ref` from this batch, the number of an existing card, or "current" for the card you are in.
- Per card or in `defaults`: status (backlog, todo), priority (high, normal, low), agent (a name from
  `task context`), verify_cmd, labels (a list of names, created if missing). Per card only:
  target_branch, start_after, start_before (ISO 8601 with a time zone), start_date, due_date (YYYY-MM-DD, a plan
  for people: the queue ignores them). A card has no model, effort or permission mode of its own: those belong to its agent, so pick another agent
  to run it differently. What the agent leaves out follows the project.
- A card goes to work only with an agent. A "todo" card that names none gets the project's default
  agent, then your own; with neither it stays in the backlog, and the response warns you.
- `"parent": ID` at the top puts every card of the batch under that card, `"no_parent": true` makes them
  top-level. Without either they are subtasks of the card you are in.
- A batch is all or nothing: on an error nothing was created, so fix it and send it again. Repeating a
  request within 24 hours returns the same cards, so a retry is safe. `--no-dedupe` creates new ones.

## The base branch of a chain

A card starts when its blockers are done, which means merged into THEIR base, and its worktree is cut
from ITS base. So a card sees a blocker's work only when both have the same base. Therefore:

- All cards of a chain share one base. Leave it out and a card inherits its blocker's. orc refuses a
  card whose explicit base differs from its blocker's, or whose blockers disagree. A blocker in another
  project is fine: repositories do not share branches, and only the order applies.
- With no blocker and no base named, a card takes the base of the card you are in, then the project's.
- For a large feature, consider a branch of its own: `target_branch` plus `create_target_from`. Merging
  it further is then the owner's decision.

## Your own card

A card you create cannot see your work until your card is merged. If it needs your work, it must wait
for you: `"depends_on": ["current"]`, or `--after current`. This includes spec and plan files: commit
them in your branch, and only files tracked by git travel. A blocker's failure holds its dependents
until it is fixed, while an archived or deleted blocker stops holding them.

Do not wait or poll for the cards you create. Your session occupies a worker slot that they may need,
so waiting can deadlock the queue. Finish your own card, and name the new cards in your final message.
If your own card truly cannot go on until another card is done, run `{cmd} task wakeup --card ID
--note "what to check"` as the last action of your turn instead of polling: your session is shut down,
frees its slot, and resumes in the same worktree when that card is done, fails or goes away. `--in 2h`
or `--at TIME` alone wakes you at a time, and added to `--card` sets a deadline.

## Decomposing a feature

1. Large or unclear feature: write a spec first. Then a plan, using a planning skill such as
   superpowers:writing-plans if you have one. A small feature needs no spec.
2. Big plan: split it into sections, in one file or several. A short plan stays in one file. Either way
   the implementation runs in separate cards, one per section or step.
3. Commit the spec and the plan. Create one card per step, in order, on one base, with the first waiting
   for "current" so the files are there when it starts.
4. Write every assignment for a reader with no context: what to build, the path of the plan file and
   the section to implement, what is done when, and how to verify it. Name a section, do not paste it.
5. Pick the executor per card: `task context` lists the agents and their roles. Hard or risky steps go
   to a stronger agent, routine ones to a cheaper one.

Size a card so that it can be verified and merged alone, and leaves the base branch working: the next
card builds on it. Steps that touch different files may run in parallel, so make them wait only for what
they really need. Parallel cards can still conflict when merging.

## Limits

At most {max_batch} cards per batch and {max_caller} per calling card. A chain of agents creating agents can
go {max_generation} generations deep on its own: past that, new cards may only go to the backlog, for the
owner to decide. If you hit one of these, stop and say so rather than looking for a way around it.
"""


def guide(data_dir: Path) -> str:
    from orc.task_plans import MAX_AUTOSTART_GENERATION, MAX_BATCH_TASKS, MAX_TASKS_PER_CALLER

    return GUIDE.format(cmd=cli_command(data_dir), max_batch=MAX_BATCH_TASKS, max_caller=MAX_TASKS_PER_CALLER,
                        max_generation=MAX_AUTOSTART_GENERATION)


def skill_text(data_dir: Path) -> str:
    """A Claude Code skill: it lets a session outside orc find this when asked to plan work into cards."""
    return (f"---\nname: {SKILL_NAME}\ndescription: Create and manage tasks on the orc (orchestrator) board from a session: one card, "
            f"several linked cards, a parameter set or an agent per card, a chain on one base branch; list, show, edit, "
            f"move to another project, archive or delete existing cards. Use when asked to put work on the orc board or "
            f"backlog, to decompose a feature or a plan into cards that run in order, or to change, move or remove cards.\n---\n\n"
            f"{SKILL_MARKER}\n\n{guide(data_dir)}")


def install_skill(data_dir: Path, skills_dir: Path, force: bool = False) -> Path:
    """Write the skill into a skills directory. A file of the same name that orc did not write is
    someone's own work: it is not overwritten without an explicit force."""
    path = skills_dir / SKILL_NAME / "SKILL.md"
    if path.exists() and not force and SKILL_MARKER not in path.read_text(encoding="utf-8", errors="replace"):
        raise FileExistsError(f"{path} exists and was not written by orc: pass --force to overwrite it")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(skill_text(data_dir), encoding="utf-8")
    return path
